/* =========================================================================
   GitHub Pages demo layer — swaps the live Flask API for an in-memory
   mock backed by DEMO_DB (real scan data captured from a full run
   against the bundled vulnerable demo target).

   Load order in index.html:  api.js -> charts.js -> demo-data.js ->
   demo.js -> app.js   (this file patches API.* before the SPA boots).
   ========================================================================= */
window.SENTINEL_DEMO = true;
const D = DEMO_DB;

const allFindings = () => Object.values(D.findings).flat();

const findScan = (id) => D.scans.find((s) => s.id === id);

/* ------------------------------- mock API ------------------------------- */
API.get = async (u) => {
  const path = u.split('?')[0];
  if (path === '/api/health')
    return { service: 'sentinel-ai', version: '1.0.0', ai_backend: 'sentinel-mind', demo_target: 'static-demo' };
  if (path === '/api/scans') return { scans: D.scans };
  if (path === '/api/alerts') return { alerts: D.alerts };

  let m = path.match(/^\/api\/scans\/([^/]+)$/);
  if (m) {
    const s = findScan(m[1]);
    if (!s) throw new Error('scan not found in demo data');
    const copy = JSON.parse(JSON.stringify(s));
    copy.alerts = D.alerts.filter((a) => a.scan_id === s.id).slice(0, 5);
    return copy;
  }
  m = path.match(/^\/api\/scans\/([^/]+)\/findings$/);
  if (m) return {
    findings: D.findings[m[1]] || [],
    counts: (findScan(m[1]) || {}).summary?.counts || {},
  };
  m = path.match(/^\/api\/scans\/([^/]+)\/tests$/);
  if (m) return { tests: D.tests[m[1]] || [] };
  throw new Error('demo mode: endpoint offline');
};

API.post = async (u, body) => {
  const path = u.split('?')[0];
  if (path === '/api/alerts/read') { D.alerts.forEach((a) => (a.read = 1)); return { ok: true }; }
  if (path.endsWith('/analyze')) {
    const f = allFindings().find((x) => x.id === (body || {}).finding_id);
    if (!f) throw new Error('finding not found');
    return {
      explanation: f.ai_explanation,
      fix_conceptual: f.ai_fix,
      fix_code: f.ai_fix_code || f.ai_analysis?.fix_code,
      learning: f.ai_learning,
    };
  }
  if (path === '/api/ai/assistant') {
    const f = (body || {}).finding_id && allFindings().find((x) => x.id === body.finding_id);
    const l = (f && f.ai_learning) || {};
    if (l.mistake) return {
      answer: `Mistake: ${l.mistake}\n\nBest practice: ${l.best_practice}\n\nWhy it matters: ${l.why}\n\n(Full conversational AI is available when the backend runs with an LLM key.)`,
      backend: 'demo',
    };
    return { answer: 'This is a static demo of Sentinel AI. Run "python app.py --with-demo" locally to scan your own authorized targets with the full pipeline.', backend: 'demo' };
  }
  if (path === '/api/scans')
    throw new Error('Static demo — run "python app.py --with-demo" locally to launch live scans.');
  if (path.startsWith('/api/monitor/') || path.startsWith('/api/scans/'))
    throw new Error('Static demo — this action requires the backend running locally.');
  throw new Error('demo mode: endpoint offline');
};

/* ----------------------- report download (client-side) ------------------
   The real reports are generated by the Flask backend; in demo mode we
   reconstruct equivalent HTML from the embedded scan data. */
function demoDownloadReport(scanId, fmt) {
  const s = findScan(scanId);
  if (!s) return UI.toast('Scan not in demo data', true);
  const findings = D.findings[scanId] || [];
  const sum = s.summary || {};
  const esc = (v) => String(v ?? '').replace(/[&<>]/g, (c) => ({ '&': '&am' + 'p;', '<': '&l' + 't;', '>': '&g' + 't;' }[c]));

  let body = '';
  if (fmt === 'developer') {
    body = `<h1>Sentinel AI — Developer Report</h1>
      <p>Target: <b>${esc(s.target)}</b> · scan ${s.id} · ${new Date((s.finished_at || 0) * 1000).toISOString().slice(0, 16).replace('T', ' ')} UTC</p>
      <p>${esc(sum.ai_summary?.executive_summary || '')}</p>
      ${findings.map((f) => `
        <h2 style="color:#ff3b5c">${esc(f.title)} [${f.severity}]</h2>
        <p><b>${esc(f.method)} ${esc(f.endpoint)}</b> — ${esc(f.evidence)}</p>
        <p>${esc(f.ai_explanation || '')}</p>
        <pre>${esc(f.ai_fix_code || f.ai_analysis?.fix_code || '')}</pre>`).join('')}`;
  } else if (fmt === 'client') {
    body = `<h1>Sentinel AI — Client Report</h1>
      <h2>In plain language</h2><p>${esc(sum.ai_summary?.executive_summary || '')}</p>
      <h2>Issues found</h2>
      ${findings.map((f) => `<p><b>[${f.severity.toUpperCase()}] ${esc(f.title)}</b> at ${esc(f.endpoint)}</p>`).join('')}
      <h2>Recommendations</h2>
      <ol>${(sum.ai_summary?.recommendations || []).map((r) => `<li>${esc(r)}</li>`).join('')}</ol>`;
  } else {
    const blob = new Blob([JSON.stringify({ scan: s, findings }, null, 2)], { type: 'application/json' });
    return triggerDownload(blob, `sentinel-${scanId}-export.json`);
  }
  triggerDownload(new Blob([`<html><head><meta charset="utf-8"><title>Sentinel AI report</title>
    <style>body{font:14px/1.6 'Segoe UI',sans-serif;background:#0a0e14;color:#e6edf3;padding:40px;max-width:900px;margin:auto}
    h1{color:#00e5a0}pre{background:#101623;padding:12px;border-radius:8px;overflow:auto;color:#9fe8c9}</style>
    </head><body>${body}<p style="color:#8b95a5;font-size:11px;margin-top:40px">Generated from the static GitHub Pages demo — identical reports are produced server-side by the full backend.</p></body></html>`],
    { type: 'text/html' }), `sentinel-${scanId}-${fmt}-report.html`);
}

function triggerDownload(blob, name) {
  const a = document.createElement('a');
  a.href = URL.createObjectURL(blob);
  a.download = name;
  document.body.appendChild(a);
  a.click();
  a.remove();
  UI.toast('Report downloaded ✔');
}

/* Intercept clicks on /api/... report links and serve them from demo data. */
document.addEventListener('click', (ev) => {
  const a = ev.target.closest('a[href^="/api/"]');
  if (!a) return;
  const m = (a.getAttribute('href') || '').match(/^\/api\/scans\/([^/]+)\/report\?format=(\w+)$/);
  ev.preventDefault();
  if (!m) return UI.toast('Demo mode — backend features need the local stack.', true);
  demoDownloadReport(m[1], m[2]);
});

